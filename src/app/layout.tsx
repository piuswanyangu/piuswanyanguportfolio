import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { FloatingActions } from "@/components/layout/floating-actions";
import { Footer } from "@/components/layout/footer";
import { Header } from "@/components/layout/header";
import { ScrollReveal } from "@/components/layout/scroll-reveal";
import { getSocialLinks } from "@/components/layout/social-links";
import { StructuredData } from "@/components/seo/structured-data";
import type { JsonLdValue } from "@/components/seo/structured-data";
import { absoluteUrl, siteConfig } from "@/lib/site-config";
import "./globals.css";

const themeInitializer = `
  (function () {
    var root = document.documentElement;
    var preference = "light";
    try {
      var stored = localStorage.getItem("afrinex-theme");
      if (stored === "light" || stored === "dark" || stored === "green") preference = stored;
    } catch (_) {}
    root.dataset.theme = preference;
    root.dataset.themePreference = preference;
    root.style.colorScheme = preference === "light" ? "light" : "dark";
  })();
`;

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

/** Home page search title and description. */
const homeTitle = "Afrinex Solutions | Digital, Software & AI Services in Kenya";
const homeDescription =
  "Kenya-based Afrinex Solutions helps individuals and businesses with KRA and SHA online services, data, websites, software, AI and automation.";

export const metadata: Metadata = {
  metadataBase: siteConfig.url,
  title: {
    default: homeTitle,
    template: "%s | Afrinex Solutions",
  },
  description: homeDescription,
  applicationName: "Afrinex Solutions",
  authors: [{ name: "Afrinex Solutions" }],
  creator: "Afrinex Solutions",
  keywords: [
    "Digital Services",
    "Software Development",
    "AI-Powered Solutions",
    "Business Automation",
    "Data Services",
    "Online Service Assistance",
  ],
  openGraph: {
    title: homeTitle,
    description: homeDescription,
    siteName: "Afrinex Solutions",
    type: "website",
    url: "/",
    images: siteConfig.socialImage
      ? [{ url: siteConfig.socialImage, alt: "Afrinex Solutions" }]
      : undefined,
  },
  twitter: {
    card: "summary_large_image",
    title: homeTitle,
    description: homeDescription,
    images: siteConfig.socialImage ? [siteConfig.socialImage] : undefined,
  },
};

const structuredData: JsonLdValue = {
  "@context": "https://schema.org",
  "@graph": [
    {
      "@type": "WebSite",
      "@id": absoluteUrl("/#website"),
      url: absoluteUrl("/"),
      name: siteConfig.name,
      description: siteConfig.description,
      inLanguage: "en",
      publisher: { "@id": absoluteUrl("/#organization") },
    },
    {
      "@type": ["Organization", "ProfessionalService"],
      "@id": absoluteUrl("/#organization"),
      name: siteConfig.name,
      url: absoluteUrl("/"),
      // Google requires a raster logo (PNG/JPG, at least 112 x 112 px).
      // /apple-icon is the 180 x 180 PNG generated by src/app/apple-icon.tsx.
      logo: absoluteUrl("/apple-icon"),
      image: absoluteUrl("/opengraph-image"),
      email: siteConfig.contact.email,
      telephone: siteConfig.contact.phone,
      description: siteConfig.description,
      address: {
        "@type": "PostalAddress",
        addressCountry: "KE",
      },
      areaServed: [{ "@type": "Country", name: siteConfig.contact.location }],
      sameAs: getSocialLinks()
        .filter((link) => link.icon !== "whatsapp")
        .map((link) => link.href),
      founder: {
        "@type": "Person",
        name: siteConfig.founder.name,
        jobTitle: siteConfig.founder.role,
      },
    },
  ],
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeInitializer }} />
      </head>
      <body className="theme-transition flex min-h-screen flex-col">
        <StructuredData data={structuredData} />
        <a href="#main-content" className="skip-link">
          Skip to main content
        </a>
        <Header />
        <main id="main-content" tabIndex={-1} className="flex-1 focus:outline-none">
          {children}
        </main>
        <Footer />
        <FloatingActions />
        <ScrollReveal />
      </body>
    </html>
  );
}
